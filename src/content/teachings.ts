/** Băm FNV-1a 32-bit cho chuỗi, trả về số nguyên không âm. */
function fnv1a(str: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Lời dạy của ngày, xác định theo `dayKey` (ví dụ '2026-05-12'). */
export function teachingOfDay(dayKey: string): string {
  return TEACHINGS[fnv1a(String(dayKey)) % TEACHINGS.length];
}

/** Lời nhắc theo ngày; `drawIndex` (có thể âm hoặc rất lớn) dùng để rút lời nhắc khác trong cùng ngày. */
export function reminderFor(dayKey: string, drawIndex = 0): Reminder {
  const n = REMINDERS.length;
  const d = Number.isFinite(drawIndex) ? Math.floor(drawIndex) : 0;
  const idx = (((fnv1a(String(dayKey)) + (d % n)) % n) + n) % n;
  return REMINDERS[idx];
}
